import * as THREE from 'three';
import {
  woodTexture,
  damaskTexture,
  marbleTexture,
  velvetTexture,
  linenTexture,
  petalTexture,
} from './textures.js';

/**
 * Shared PBR material library. Created once and reused everywhere so the
 * GPU only compiles each shader program a single time.
 */
export function createMaterials() {
  const velvetMap = velvetTexture();

  const m = {
    gold: new THREE.MeshPhysicalMaterial({
      color: 0xd8ad6a,
      metalness: 1,
      roughness: 0.22,
      clearcoat: 0.4,
      clearcoatRoughness: 0.2,
      envMapIntensity: 1.3,
    }),
    // brushed gold for fixtures that sit right next to point lights
    chandGold: new THREE.MeshStandardMaterial({
      color: 0xc9a066,
      metalness: 1,
      roughness: 0.4,
      envMapIntensity: 1.1,
    }),
    goldSatin: new THREE.MeshStandardMaterial({
      color: 0xc49a65,
      metalness: 1,
      roughness: 0.42,
      envMapIntensity: 1,
    }),
    ringGold: new THREE.MeshPhysicalMaterial({
      color: 0xf0c98a,
      metalness: 1,
      roughness: 0.08,
      clearcoat: 1,
      clearcoatRoughness: 0.05,
      envMapIntensity: 1.4,
    }),
    door: new THREE.MeshStandardMaterial({
      map: woodTexture({ base: '#3a1a0e', grain: '#160703', seed: 4 }),
      roughness: 0.48,
      metalness: 0.0,
      envMapIntensity: 0.7,
    }),
    darkWood: new THREE.MeshStandardMaterial({
      map: woodTexture({ base: '#1d0b07', grain: '#0a0302', seed: 8 }),
      roughness: 0.38,
      metalness: 0.0,
    }),
    stone: new THREE.MeshStandardMaterial({ color: 0x1b0d0f, roughness: 0.85, metalness: 0 }),
    wall: new THREE.MeshStandardMaterial({
      map: damaskTexture(),
      roughness: 0.75,
      metalness: 0.05,
      envMapIntensity: 0.4,
    }),
    wainscot: new THREE.MeshStandardMaterial({
      map: woodTexture({ base: '#1a0709', grain: '#090203', seed: 15, repeat: [8, 1] }),
      roughness: 0.32,
      metalness: 0.05,
    }),
    ceiling: new THREE.MeshStandardMaterial({ color: 0x12040a, roughness: 0.9 }),
    floor: new THREE.MeshPhysicalMaterial({
      map: marbleTexture(),
      roughness: 0.14,
      metalness: 0.0,
      clearcoat: 1,
      clearcoatRoughness: 0.08,
      envMapIntensity: 0.12,
    }),
    carpet: new THREE.MeshPhysicalMaterial({
      color: 0x4a0a18,
      roughness: 1,
      sheen: 1,
      sheenRoughness: 0.5,
      sheenColor: new THREE.Color(0xa0344d),
      roughnessMap: velvetMap,
    }),
    velvet: new THREE.MeshPhysicalMaterial({
      color: 0x4d0a1a,
      roughness: 0.95,
      roughnessMap: velvetMap,
      sheen: 1,
      sheenRoughness: 0.35,
      sheenColor: new THREE.Color(0xc0455e),
      envMapIntensity: 0.6,
    }),
    ringVelvet: new THREE.MeshPhysicalMaterial({
      color: 0x5a0b1e,
      roughness: 0.9,
      roughnessMap: velvetMap,
      sheen: 1,
      sheenRoughness: 0.28,
      sheenColor: new THREE.Color(0xe0607a),
    }),
    satinCushion: new THREE.MeshPhysicalMaterial({
      color: 0x8a6f58,
      roughness: 0.55,
      sheen: 0.8,
      sheenColor: new THREE.Color(0xffffff),
      sheenRoughness: 0.3,
    }),
    curtain: new THREE.MeshPhysicalMaterial({
      color: 0x3e0814,
      roughness: 0.9,
      sheen: 1,
      sheenRoughness: 0.4,
      sheenColor: new THREE.Color(0xb23a55),
      side: THREE.DoubleSide,
    }),
    linen: new THREE.MeshPhysicalMaterial({
      map: linenTexture(),
      color: 0xe6d9c6, // warm ivory rather than paper white, so it doesn't glare under the key light
      roughness: 0.82,
      sheen: 0.4,
      sheenColor: new THREE.Color(0xfff6e8),
      side: THREE.DoubleSide,
    }),
    burgundyCloth: new THREE.MeshPhysicalMaterial({
      map: linenTexture({ color: '#5a0d1e' }),
      roughness: 0.8,
      sheen: 0.8,
      sheenColor: new THREE.Color(0xb54960),
      side: THREE.DoubleSide,
    }),
    porcelain: new THREE.MeshPhysicalMaterial({
      color: 0xf6eee4,
      roughness: 0.15,
      clearcoat: 1,
      clearcoatRoughness: 0.05,
    }),
    glass: new THREE.MeshPhysicalMaterial({
      color: 0xffffff,
      metalness: 0,
      roughness: 0.03,
      transmission: 1,
      thickness: 0.02,
      ior: 1.5,
      envMapIntensity: 1.6,
      transparent: true,
      side: THREE.DoubleSide,
      specularIntensity: 1,
    }),
    vaseGlass: new THREE.MeshPhysicalMaterial({
      color: 0xf2dcc8,
      metalness: 0,
      roughness: 0.04,
      transmission: 1,
      thickness: 0.15,
      ior: 1.5,
      envMapIntensity: 1.3,
      transparent: true,
    }),
    // clear candle-holder glass: a thin see-through shell so the flame inside shows
    votiveGlass: new THREE.MeshPhysicalMaterial({
      color: 0xfff6ec,
      metalness: 0,
      roughness: 0.04,
      transparent: true,
      opacity: 0.2,
      ior: 1.5,
      specularIntensity: 1,
      clearcoat: 1,
      clearcoatRoughness: 0.03,
      envMapIntensity: 2.2,
      depthWrite: false,
      side: THREE.DoubleSide,
    }),
    // opaque on purpose: transmissive glass only "sees" opaque objects behind it
    wine: new THREE.MeshPhysicalMaterial({
      color: 0x3d0510,
      roughness: 0.08,
      clearcoat: 1,
      clearcoatRoughness: 0.03,
      sheen: 0.6,
      sheenColor: new THREE.Color(0xa0102a),
      emissive: new THREE.Color(0x4a0612),
      emissiveIntensity: 0.25,
    }),
    water: new THREE.MeshPhysicalMaterial({
      color: 0xffffff,
      roughness: 0.02,
      transmission: 1,
      thickness: 0.1,
      ior: 1.33,
      transparent: true,
    }),
    wax: new THREE.MeshPhysicalMaterial({
      color: 0xf4e8dc,
      roughness: 0.55,
      transmission: 0.0,
      sheen: 0.4,
      sheenColor: new THREE.Color(0xffe2b8),
      emissive: new THREE.Color(0xff9a40),
      emissiveIntensity: 0.06,
    }),
    wick: new THREE.MeshBasicMaterial({ color: 0x1a0d08 }),
    rose: new THREE.MeshPhysicalMaterial({
      map: petalTexture(),
      vertexColors: true, // shading towards the heart of the bloom
      emissive: new THREE.Color(0x3a0310), // a hint of light passing through the petals
      emissiveIntensity: 0.18,
      roughness: 0.58,
      sheen: 1,
      sheenRoughness: 0.35,
      sheenColor: new THREE.Color(0xff4d6a),
      side: THREE.DoubleSide,
      envMapIntensity: 0.6,
    }),
    petal: new THREE.MeshPhysicalMaterial({
      map: petalTexture(),
      emissive: new THREE.Color(0x4a0614), // a whisper of glow so petals read against the dark
      emissiveIntensity: 0.25,
      roughness: 0.6,
      sheen: 1,
      sheenRoughness: 0.35,
      sheenColor: new THREE.Color(0xff5a74),
      side: THREE.DoubleSide,
    }),
    leaf: new THREE.MeshPhysicalMaterial({ color: 0x173a19, roughness: 0.42, sheen: 0.5, sheenColor: new THREE.Color(0x6f9a52), clearcoat: 0.25, clearcoatRoughness: 0.5, side: THREE.DoubleSide }),
    stem: new THREE.MeshPhysicalMaterial({ color: 0x24431c, roughness: 0.5, clearcoat: 0.2 }),
    thorn: new THREE.MeshStandardMaterial({ color: 0x5a2a1a, roughness: 0.6 }),
    bulb: new THREE.MeshBasicMaterial({ color: new THREE.Color(1.0, 0.75, 0.42).multiplyScalar(1.6) }),
    crystal: new THREE.MeshPhysicalMaterial({
      color: 0xffffff,
      metalness: 0,
      roughness: 0,
      transmission: 1,
      thickness: 0.02,
      ior: 1.9,
      envMapIntensity: 2.5,
      flatShading: true,
    }),
    mirror: new THREE.MeshStandardMaterial({ color: 0x2a1a16, metalness: 1, roughness: 0.08, envMapIntensity: 1.2 }),
    doorLight: new THREE.MeshBasicMaterial({ color: new THREE.Color(1.0, 0.6, 0.28).multiplyScalar(0.62) }),
  };
  return m;
}
